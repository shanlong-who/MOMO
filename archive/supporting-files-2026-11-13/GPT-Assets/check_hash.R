library(digest)
path <- normalizePath("Releases/2.0.0/Source/assets/aligned/momo-atlas.png", winslash = "/")
print(file.exists(path))
print(file.access(path, 4L))
print(file.info(path)[, c("size", "mode", "isdir")])
connection <- file(path, "rb")
bytes <- readBin(connection, "raw", n = file.info(path)$size)
close(connection)
cat("Read bytes:", length(bytes), "\n")
print(try(digest(file = path, algo = "sha256")))
print(digest(bytes, algo = "sha256", serialize = FALSE))
